class NumberedCanvas:
    """Canvas wrapper to handle professional page numbering."""

    def __init__(self, *args, **kwargs):
        pass


def generate_pdf_report(data: Dict[str, Any]) -> bytes:
    """
    Generate a professional PDF assessment report from the analysis payload.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=40,
        rightMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    primary_color = colors.HexColor("#0f172a")  # Slate 900
    secondary_color = colors.HexColor("#334155")  # Slate 700
    muted_color = colors.HexColor("#64748b")  # Slate 500
    border_color = colors.HexColor("#cbd5e1")  # Slate 300
    bg_card_color = colors.HexColor("#f8fafc")  # Slate 50
    accent_color = colors.HexColor("#0284c7")  # Sky 600

    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=primary_color,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=muted_color,
    )
    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=primary_color,
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "BodyTextCustom",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=secondary_color,
    )
    bold_label_style = ParagraphStyle(
        "BoldLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=13,
        textColor=primary_color,
    )
    bullet_style = ParagraphStyle(
        "BulletText",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=secondary_color,
        leftIndent=12,
        firstLineIndent=-12,
    )
    score_big_style = ParagraphStyle(
        "ScoreBig",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=30,
        leading=32,
        textColor=accent_color,
        alignment=1,  # Centered
    )
    score_sub_style = ParagraphStyle(
        "ScoreSub",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=muted_color,
        alignment=1,
    )

    story: List[Any] = []

    # 1. Header
    story.append(Paragraph("SOCIAL MEDIA CONTENT ANALYSIS REPORT", title_style))
    story.append(Paragraph(f"Generated by Social Media Content Analyzer · {datetime.now().strftime('%B %d, %Y, %H:%M')}", subtitle_style))
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=1, color=border_color, spaceBefore=2, spaceAfter=10))

    # 2. Metadata & Score Row
    file_info = data.get("file_info", {})
    score_info = data.get("score", {})
    metrics_info = data.get("metrics", {})
    ai_info = data.get("ai_review", {})

    filename = file_info.get("filename", "Uploaded Content")
    file_type = file_info.get("file_type", "Document").upper()
    method = file_info.get("extraction_method", "Text Extraction")
    total_score = score_info.get("total_score", 0)
    verdict = score_info.get("verdict", "")

    meta_content = [
        [Paragraph("Document / File:", bold_label_style), Paragraph(str(filename), body_style)],
        [Paragraph("Extraction Type:", bold_label_style), Paragraph(f"{file_type} ({method})", body_style)],
        [Paragraph("Analysis Date:", bold_label_style), Paragraph(datetime.now().strftime("%Y-%m-%d %H:%M:%S"), body_style)],
        [Paragraph("AI Engine:", bold_label_style), Paragraph(f"Gemini Structured ({ai_info.get('ai_status', 'active')})", body_style)],
    ]
    meta_table = Table(meta_content, colWidths=[100, 240])
    meta_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
    ]))

    score_box_content = [
        [Paragraph("ENGAGEMENT SCORE", score_sub_style)],
        [Paragraph(f"{total_score}<font size=14 color='#64748b'>/100</font>", score_big_style)],
        [Paragraph("Readiness Heuristic", score_sub_style)],
    ]
    score_box_table = Table(score_box_content, colWidths=[170])
    score_box_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg_card_color),
        ("BOX", (0, 0), (-1, -1), 1, border_color),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))

    top_summary_table = Table([[meta_table, score_box_table]], colWidths=[350, 180])
    top_summary_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN", (1, 0), (1, 0), "RIGHT"),
    ]))
    story.append(top_summary_table)

    if verdict:
        story.append(Spacer(1, 6))
        verdict_para = Paragraph(f"<b>Assessment Verdict:</b> {verdict}", body_style)
        verdict_table = Table([[verdict_para]], colWidths=[530])
        verdict_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), bg_card_color),
            ("BOX", (0, 0), (-1, -1), 0.5, border_color),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(verdict_table)

    # 3. Content Metrics Snapshot
    story.append(Spacer(1, 8))
    story.append(Paragraph("CONTENT METRICS SNAPSHOT", section_heading))

    metrics_table_data = [
        [
            Paragraph("<b>Words:</b>", body_style), Paragraph(str(metrics_info.get("word_count", 0)), body_style),
            Paragraph("<b>Characters:</b>", body_style), Paragraph(str(metrics_info.get("character_count", 0)), body_style),
            Paragraph("<b>Sentences:</b>", body_style), Paragraph(str(metrics_info.get("sentence_count", 0)), body_style),
        ],
        [
            Paragraph("<b>Paragraphs:</b>", body_style), Paragraph(str(metrics_info.get("paragraph_count", 0)), body_style),
            Paragraph("<b>Hashtags:</b>", body_style), Paragraph(str(metrics_info.get("hashtag_count", 0)), body_style),
            Paragraph("<b>Mentions:</b>", body_style), Paragraph(str(metrics_info.get("mention_count", 0)), body_style),
        ],
        [
            Paragraph("<b>URLs:</b>", body_style), Paragraph(str(metrics_info.get("url_count", 0)), body_style),
            Paragraph("<b>Questions:</b>", body_style), Paragraph("Yes" if metrics_info.get("has_question") else "None", body_style),
            Paragraph("<b>Readability:</b>", body_style), Paragraph(f"{metrics_info.get('readability_score', 0)} ({metrics_info.get('readability_grade', 'N/A')})", body_style),
        ],
    ]
    m_table = Table(metrics_table_data, colWidths=[80, 95, 80, 95, 80, 100])
    m_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg_card_color),
        ("GRID", (0, 0), (-1, -1), 0.5, border_color),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(m_table)

    # 4. Overall Assessment & Core Review
    story.append(Spacer(1, 8))
    story.append(Paragraph("EDITORIAL REVIEW & SEMANTIC ANALYSIS", section_heading))

    overall_text = ai_info.get("overall_assessment", "Analysis not available.")
    story.append(Paragraph(overall_text, body_style))
    story.append(Spacer(1, 6))

    # Strengths & Areas for Improvement side-by-side
    strengths_items = [Paragraph(f"• {s}", bullet_style) for s in ai_info.get("strengths", [])]
    weakness_items = [Paragraph(f"• {w}", bullet_style) for w in ai_info.get("areas_for_improvement", [])]

    if not strengths_items:
        strengths_items = [Paragraph("• No specific strengths highlighted.", bullet_style)]
    if not weakness_items:
        weakness_items = [Paragraph("• No major weaknesses detected.", bullet_style)]

    sw_table_data = [
        [Paragraph("<b>Key Strengths</b>", bold_label_style), Paragraph("<b>Areas for Improvement</b>", bold_label_style)],
        [strengths_items, weakness_items],
    ]
    sw_table = Table(sw_table_data, colWidths=[260, 260])
    sw_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BACKGROUND", (0, 0), (-1, -1), bg_card_color),
        ("BOX", (0, 0), (-1, -1), 0.5, border_color),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, border_color),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(sw_table)

    # 5. Engagement & Dimension Analysis
    story.append(Spacer(1, 8))
    story.append(Paragraph("DIMENSIONAL ENGAGEMENT EVALUATION", section_heading))

    dim_data = [
        [Paragraph("<b>Hook / Opening:</b>", bold_label_style), Paragraph(ai_info.get("hook_analysis", "N/A"), body_style)],
        [Paragraph("<b>Clarity & Cadence:</b>", bold_label_style), Paragraph(ai_info.get("clarity_analysis", "N/A"), body_style)],
        [Paragraph("<b>Engagement Prompts:</b>", bold_label_style), Paragraph(ai_info.get("engagement_analysis", "N/A"), body_style)],
        [Paragraph("<b>Call-to-Action:</b>", bold_label_style), Paragraph(ai_info.get("cta_analysis", "N/A"), body_style)],
        [Paragraph("<b>Audience & Tone:</b>", bold_label_style), Paragraph(f"Tone: {ai_info.get('tone', 'N/A')} — {ai_info.get('audience_analysis', '')}", body_style)],
    ]
    dim_table = Table(dim_data, colWidths=[130, 390])
    dim_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.5, border_color),
        ("BACKGROUND", (0, 0), (0, -1), bg_card_color),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(dim_table)

    # 6. Actionable Recommendations
    suggestions = ai_info.get("suggestions", [])
    if suggestions:
        story.append(Spacer(1, 8))
        story.append(Paragraph("ACTIONABLE RECOMMENDATIONS", section_heading))

        sug_rows = []
        for idx, sug in enumerate(suggestions, start=1):
            title = sug.get("title", f"Recommendation {idx}")
            issue = sug.get("issue", "")
            rec = sug.get("recommendation", "")
            reason = sug.get("reason", "")

            sug_content = [
                Paragraph(f"<b>{idx}. {title}</b>", bold_label_style),
                Paragraph(f"<b>Issue:</b> {issue}", body_style),
                Paragraph(f"<b>Recommendation:</b> {rec}", body_style),
                Paragraph(f"<b>Why it matters:</b> {reason}", subtitle_style),
            ]
            sug_rows.append([sug_content])

        sug_table = Table(sug_rows, colWidths=[520])
        sug_table.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("BACKGROUND", (0, 0), (-1, -1), bg_card_color),
            ("BOX", (0, 0), (-1, -1), 0.5, border_color),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, border_color),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(KeepTogether(sug_table))

    # 7. Improved Post Version
    improved_post = ai_info.get("improved_post", "")
    if improved_post:
        story.append(Spacer(1, 8))
        story.append(Paragraph("IMPROVED POST (STRATEGIC REWRITE)", section_heading))

        # Format paragraphs cleanly
        improved_paras = [Paragraph(p.replace("\n", "<br/>"), body_style) for p in improved_post.split("\n\n") if p.strip()]
        improved_table = Table([[improved_paras]], colWidths=[520])
        improved_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), bg_card_color),
            ("BOX", (0, 0), (-1, -1), 1, border_color),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ]))
        story.append(KeepTogether(improved_table))

    # Build PDF
    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


