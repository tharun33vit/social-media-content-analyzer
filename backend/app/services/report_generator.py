def _set_cell_background(cell, fill_hex: str) -> None:
    """Helper to set background color of a Word table cell."""
    tcPr = cell._element.get_or_add_tcPr()
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{fill_hex}"/>')
    tcPr.append(shd)


def generate_docx_report(data: Dict[str, Any]) -> bytes:
    """
    Generate a professional Word (.docx) assessment report from the analysis payload.
    """
    doc = Document()

    # Page Margins (0.6 in)
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(0.6)
        section.bottom_margin = Inches(0.6)
        section.left_margin = Inches(0.6)
        section.right_margin = Inches(0.6)

    # Document Title
    title_p = doc.add_paragraph()
    title_run = title_p.add_run("Social Media Content Analysis Report")
    title_run.font.name = "Arial"
    title_run.font.size = Pt(20)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(15, 23, 42)

    sub_p = doc.add_paragraph()
    sub_run = sub_p.add_run(f"Generated by Social Media Content Analyzer · {datetime.now().strftime('%B %d, %Y, %H:%M')}")
    sub_run.font.name = "Arial"
    sub_run.font.size = Pt(9.5)
    sub_run.font.color.rgb = RGBColor(100, 116, 139)

    doc.add_paragraph().paragraph_format.space_after = Pt(4)

    file_info = data.get("file_info", {})
    score_info = data.get("score", {})
    metrics_info = data.get("metrics", {})
    ai_info = data.get("ai_review", {})

    total_score = score_info.get("total_score", 0)
    verdict = score_info.get("verdict", "")

    # Meta & Score Table
    table = doc.add_table(rows=4, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False

    meta_pairs = [
        ("Document File:", str(file_info.get("filename", "Uploaded File"))),
        ("Extraction Type:", f"{file_info.get('file_type', 'Document').upper()} ({file_info.get('extraction_method', 'Text Extraction')})"),
        ("Engagement Readiness Score:", f"{total_score} / 100 ({score_info.get('disclaimer', '')})"),
        ("AI Status:", f"Gemini Structured ({ai_info.get('ai_status', 'active')})"),
    ]

    for idx, (label, val) in enumerate(meta_pairs):
        row = table.rows[idx]
        cell_lbl, cell_val = row.cells[0], row.cells[1]
        cell_lbl.width = Inches(2.2)
        cell_val.width = Inches(4.8)
        _set_cell_background(cell_lbl, "F1F5F9")
        _set_cell_background(cell_val, "F8FAFC")

        p_lbl = cell_lbl.paragraphs[0]
        r_lbl = p_lbl.add_run(label)
        r_lbl.font.bold = True
        r_lbl.font.size = Pt(9.5)

        p_val = cell_val.paragraphs[0]
        r_val = p_val.add_run(val)
        r_val.font.size = Pt(9.5)

    if verdict:
        doc.add_paragraph().paragraph_format.space_after = Pt(2)
        vp = doc.add_paragraph()
        vr_bold = vp.add_run("Assessment Verdict: ")
        vr_bold.font.bold = True
        vr_bold.font.size = Pt(10)
        vr_text = vp.add_run(verdict)
        vr_text.font.size = Pt(10)

    # Content Metrics Section
    h2 = doc.add_heading("Content Metrics Snapshot", level=2)
    h2.paragraph_format.space_before = Pt(12)
    h2.paragraph_format.space_after = Pt(4)

    m_table = doc.add_table(rows=3, cols=6)
    m_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    m_data = [
        ("Words", str(metrics_info.get("word_count", 0)), "Chars", str(metrics_info.get("character_count", 0)), "Sentences", str(metrics_info.get("sentence_count", 0))),
        ("Paragraphs", str(metrics_info.get("paragraph_count", 0)), "Hashtags", str(metrics_info.get("hashtag_count", 0)), "Mentions", str(metrics_info.get("mention_count", 0))),
        ("URLs", str(metrics_info.get("url_count", 0)), "Questions", "Yes" if metrics_info.get("has_question") else "None", "Readability", f"{metrics_info.get('readability_score', 0)} ({metrics_info.get('readability_grade', 'N/A')})"),
    ]

    for r_idx, row_items in enumerate(m_data):
        row = m_table.rows[r_idx]
        for c_idx in range(6):
            cell = row.cells[c_idx]
            cell.width = Inches(1.16)
            text = row_items[c_idx]
            p = cell.paragraphs[0]
            r = p.add_run(text)
            r.font.size = Pt(9)
            if c_idx % 2 == 0:
                r.font.bold = True
                _set_cell_background(cell, "F1F5F9")
            else:
                _set_cell_background(cell, "F8FAFC")

    # Editorial Review
    h3 = doc.add_heading("Editorial Review & Semantic Analysis", level=2)
    h3.paragraph_format.space_before = Pt(12)
    h3.paragraph_format.space_after = Pt(4)

    p_overall = doc.add_paragraph(ai_info.get("overall_assessment", ""))
    p_overall.paragraph_format.space_after = Pt(6)

    # Strengths
    p_st = doc.add_paragraph()
    r_st = p_st.add_run("Key Strengths:")
    r_st.font.bold = True
    for s in ai_info.get("strengths", []):
        doc.add_paragraph(s, style="List Bullet")

    # Weaknesses
    p_wk = doc.add_paragraph()
    p_wk.paragraph_format.space_before = Pt(4)
    r_wk = p_wk.add_run("Areas for Improvement:")
    r_wk.font.bold = True
    for w in ai_info.get("areas_for_improvement", []):
        doc.add_paragraph(w, style="List Bullet")

    # Actionable Suggestions
    suggestions = ai_info.get("suggestions", [])
    if suggestions:
        h4 = doc.add_heading("Actionable Recommendations", level=2)
        h4.paragraph_format.space_before = Pt(12)
        h4.paragraph_format.space_after = Pt(4)

        for idx, sug in enumerate(suggestions, start=1):
            p_sug = doc.add_paragraph()
            r_num = p_sug.add_run(f"{idx}. {sug.get('title', 'Recommendation')}\n")
            r_num.font.bold = True
            r_num.font.size = Pt(10.5)

            r_iss = p_sug.add_run(f"• Issue: {sug.get('issue', '')}\n")
            r_iss.font.size = Pt(9.5)
            r_rec = p_sug.add_run(f"• Recommendation: {sug.get('recommendation', '')}\n")
            r_rec.font.size = Pt(9.5)
            r_rsn = p_sug.add_run(f"• Why it matters: {sug.get('reason', '')}")
            r_rsn.font.size = Pt(9.5)
            r_rsn.font.italic = True

    # Improved Version
    improved_post = ai_info.get("improved_post", "")
    if improved_post:
        h5 = doc.add_heading("Improved Post (Strategic Rewrite)", level=2)
        h5.paragraph_format.space_before = Pt(12)
        h5.paragraph_format.space_after = Pt(4)

        callout = doc.add_table(rows=1, cols=1)
        callout.alignment = WD_TABLE_ALIGNMENT.CENTER
        callout.rows[0].cells[0].width = Inches(7.0)
        _set_cell_background(callout.rows[0].cells[0], "F8FAFC")

        cp = callout.rows[0].cells[0].paragraphs[0]
        cr = cp.add_run(improved_post)
        cr.font.name = "Arial"
        cr.font.size = Pt(9.5)

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()
